    out.append("## 权限矩阵\n")
    out.append("| 资源 | owner | admin | analyst | viewer | auditor |")
    out.append("|---|---|---|---|---|---|")
    for r, *flags in RESOURCES:
        out.append(f"| {r} | " + " | ".join(flags) + " |")

