def render_faq() -> str:
    out = ["""# 常见问题

按提问频率排序，不按文档结构排序。答案里出现的数字都是实测值，不是估算——
凡是写"约"的地方，是因为跨语料规模会有浮动，不是没测过。
"""]
    cur = None
    for cat, q, a in FAQ:
        if cat != cur:
            out.append(f"\n## {cat}\n")
            cur = cat
        out.append(f"### 问：{q}\n")
        out.append(f"{a}\n")
    out.append(
        """
## 还有一类问题没有答案

上面 60 条都有一个确定答案。实际工单里还有一类问的是"你们这个准不准"，
它没有答案，只有口径：在 30 道可答题上结果集等价 90.0%，40 道题的拒答正确率 100%，
换成别的语料、别的业务域，这些数字都不成立。把这句话写在文档里，
比再补十条 FAQ 都有用。
"""
    )
    return "\n".join(out)


def render_runbook() -> str:
    out = ["""# 运维手册与故障处置

12 个真实发生过的场景。写法统一：现象 → 排查 → 处置 → 预防。
排查步骤按"最可能且最便宜"排序，不要一上来就看代码。
"""]
    for rid, sym, steps, fix, prevent in RUNBOOK:
        out.append(f"\n## {rid}　{sym}\n")
        out.append(f"**现象**：{sym}。")
        out.append(f"\n**排查**：{steps}。")
        out.append(f"\n**处置**：{fix}。")
        out.append(f"\n**预防**：{prevent}。\n")
    out.append(
        """
## 通用原则

**先看 trace 再看日志**。日志告诉你"有没有报错"，trace 告诉你"哪一步慢了、哪一步返回了空"。
90% 的线上问题在 trace 的 span 树里一眼能看出来，翻日志反而更慢。

**能复现再动手**。所有入口都支持 `debug=true`，它会返回完整的检索证据、生成的 SQL、
校验结果和判定理由。拿到这四样，绝大多数问题不用猜。

**不要在高峰期改配置**。热重载是原子的，但重载后第一次查询会走冷路径（缓存未命中），
耗时可能是平时的 3 倍。改配置选在低峰，或者改完立刻跑一次预热查询。
"""
    )
    return "\n".join(out)
