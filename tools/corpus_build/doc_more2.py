def render_antipatterns() -> str:
    out = ["""# 反模式清单

20 条真实踩过的坑。每条写三件事：长什么样、为什么错、正确做法。

收录标准：**错了不报错的**。会报错的错误不值得写进文档，
因为报错本身就是最好的文档。这里全是静默出错、数字看着合理、要过很久才被发现的那类。
"""]
    for pid, name, look, why, fix in PATTERNS:
        out.append(f"\n## {pid}　{name}\n")
        out.append(f"**长什么样**：{look}\n")
        out.append(f"**为什么错**：{why}\n")
        out.append(f"**正确做法**：{fix}\n")
    out.append(
        """
## 这些坑的共同点

二十条里，有十七条的错误形态是「数字偏大或偏小，但仍在合理区间」。
这就是它们难被发现的原因：一个算出 3 亿 GMV 的 SQL 会立刻被怀疑，
一个算出 1.28 亿而真实是 1 亿的 SQL 不会。

所以唯一的防线是把口径写下来，并且**用评测题把口径钉住**。
每一条反模式在本项目的评测集里至少有一道对应题——
不是为了考模型，是为了在有人改坏的时候立刻发现。
"""
    )
    return "\n".join(out)
